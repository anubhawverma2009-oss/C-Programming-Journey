#include <stdio.h>

int main() {
    int length = 10, breadth = 5;

    printf("Length = %d\n", length);
    printf("Breadth = %d\n", breadth);
    printf("Area = %d\n", length * breadth);
    printf("Perimeter = %d\n", 2 * (length + breadth));

    return 0;
}